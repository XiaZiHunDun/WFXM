/**
 * P4.2: butler session contract.
 *
 * The butler runtime keeps its own transcript. Memory is a projection over
 * finished sessions, never a replacement for this record.
 */

export type ButlerRole = "system" | "user" | "assistant" | "tool"

export interface ButlerToolCall {
  readonly id: string
  readonly name: string
  readonly args: Readonly<Record<string, unknown>>
}

export interface ButlerMessage {
  readonly role: ButlerRole
  readonly content: string
  readonly toolCalls?: readonly ButlerToolCall[]
  readonly toolCallId?: string
  readonly toolName?: string
}

export interface ButlerSessionRecord {
  readonly conversationId: string
  readonly userId: string
  readonly projectId?: string
  readonly messages: readonly ButlerMessage[]
  /** Last projected summary; regenerated by `summarize()`. */
  readonly summary?: string
  readonly createdAt: string
  readonly updatedAt: string
}

export interface ButlerSessionStore {
  load(conversationId: string): Promise<ButlerSessionRecord | null>
  save(record: ButlerSessionRecord): Promise<void>
  delete(conversationId: string): Promise<void>
}
